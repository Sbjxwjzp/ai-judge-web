import type { Project, Question, ExtraIssue } from '@/types/engine'

export function composeMock(p: Project | Record<string, never>): string {
  const parts: string[] = []
  parts.push('（模拟回答）我们做的项目是「' + (p.name || '（未填写名称）') + '」。')
  if (p.brief) parts.push('简单说：' + p.brief)
  if (p.tech) parts.push('技术方案上：' + p.tech)
  if (p.progress) parts.push('目前进展：' + p.progress)
  parts.push('这个问题我们还在推进中，具体细节我想先按现有方案说明，其他的后续会补。')
  return parts.join('')
}

